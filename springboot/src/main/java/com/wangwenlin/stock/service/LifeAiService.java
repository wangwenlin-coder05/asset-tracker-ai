    /** 落库前的统一收口：校验锚点 → 钉死考试类硬时间点 → 补齐准考证任务 → 补齐双向结局 → 实测链接。 */
    private Map<String, Object> injectLifeExamAnchors(List<Map<String, Object>> items, String text,
                                                     List<Map<String, Object>> declaredAnchors) {
        // 锚点＝联网检索得到的（模型整理的 examAnchors）＋ 从规划自身认出来的；后者在检索没命中时兜底
        List<Map<String, Object>> seeded = support.lifeExamAnchors(text, declaredAnchors);
        List<Map<String, Object>> anchors = new ArrayList<>(seeded);
        anchors.addAll(support.lifeDerivedAnchors(items, seeded));

        Map<String, Object> report = new LinkedHashMap<>();
        List<String> labels = new ArrayList<>();
        for (Map<String, Object> anchor : anchors) labels.add(str(anchor.get("subject")) + "@" + str(anchor.get("examDate")));
        report.put("anchors", labels);
        report.put("shifted", anchorExamDeadlines(items, anchors));
        // 没命中任何锚点时也照样纠正：同一截止日上既有「考试当天」节点、又有备考节点，后者必须提前
        report.put("selfShifted", shiftDeadlinesOffExamDay(items));
        report.put("tickets", ensureExamTicketNodes(items, anchors));
        report.put("outcomes", ensureExamOutcomeNodes(items, anchors));
        try {
            Map<String, Object> links = verifyPlanLinks(items);
            report.put("checked", links.get("checked"));
            report.put("dropped", links.get("dropped"));
        } catch (Exception ignored) {
            report.put("checked", 0);
            report.put("dropped", 0);
        }
        return report;
    }

    /** 模型很爱把模拟考的截止日期直接写成考试日，这里按锚点统一提前到考试前一日。 */
    private int anchorExamDeadlines(List<Map<String, Object>> items, List<Map<String, Object>> anchors) {
        int fixed = 0;
        for (Map<String, Object> item : items) {
            String horizon = support.lifeText(item.get("horizon"), 32);
            if (!LifeSupport.LIFE_DATE_RE.matcher(horizon).matches()) continue;
            Map<String, Object> anchor = null;
            for (Map<String, Object> candidate : anchors) {
                if (horizon.equals(str(candidate.get("examDate")))) { anchor = candidate; break; }
            }
            if (anchor == null) continue;
            // 真正「考试日 / 准考证 / 面试」这类节点本身就该落在考试日，不能前移
            if (LifeSupport.LIFE_EXAM_DAY_RE.matcher(str(item.get("title"))).find()) continue;
            item.put("horizon", support.lifeDateShift(anchor.get("examDate"), -1));
            fixed += 1;
        }
        if (fixed > 0) log.info("[life-anchor] {} 个备考任务的截止日期被从考试日前移到考试前一日", fixed);
        return fixed;
    }

    /** 同日既有「考试当天」节点、又有备考节点时，后者一定是排错了，统一提前一日。 */
    private int shiftDeadlinesOffExamDay(List<Map<String, Object>> items) {
        LinkedHashSet<String> examDays = new LinkedHashSet<>();
        for (Map<String, Object> item : items) {
            String horizon = support.lifeText(item.get("horizon"), 32);
            if (LifeSupport.LIFE_DATE_RE.matcher(horizon).matches()
                    && LifeSupport.LIFE_EXAM_DAY_RE.matcher(str(item.get("title"))).find()) {
                examDays.add(horizon);
            }
        }
        if (examDays.isEmpty()) return 0;
        int fixed = 0;
        for (Map<String, Object> item : items) {
            String horizon = support.lifeText(item.get("horizon"), 32);
            if (!examDays.contains(horizon)) continue;
            String title = str(item.get("title"));
            if (LifeSupport.LIFE_EXAM_DAY_RE.matcher(title).find()) continue;
            if (!LifeSupport.LIFE_PREP_RE.matcher(title).find()) continue;
            item.put("horizon", support.lifeDateShift(horizon, -1));
            fixed += 1;
        }
        if (fixed > 0) log.info("[life-anchor] {} 个备考任务的截止日期与「考试当天」撞车，已自动提前到前一日", fixed);
        return fixed;
    }

