    /** 等价 JS 的 {@code Math.max(0, Math.min(999, Math.round(Number(v) || 0)))}。 */
    private static int clampStep(Object value) {
        return (int) Math.max(0, Math.min(999, Math.round(JsValues.parseOrZero(value))));
    }

    /** 等价 JS 的 {@code a || b}：前值为假（null / '' / 0 / false）时取后值。 */
    private static Object jsOr(Object primary, Object fallback) {
        return truthy(primary) ? primary : fallback;
    }

