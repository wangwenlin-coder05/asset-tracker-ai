    /** 落库前实测每个唯一网址：最多测 12 个、并发 4、单个 6 秒，死链在原文里降级成文字提示。 */
    private Map<String, Object> verifyPlanLinks(List<Map<String, Object>> items) {
        List<String> urls = new ArrayList<>();
        for (Map<String, Object> item : items) {
            for (String field : List.of("detail", "risk")) {
                for (String url : support.lifeUrlsIn(item.get(field))) {
                    if (!urls.contains(url)) urls.add(url);
                }
            }
        }
        List<String> list = new ArrayList<>();
        for (int i = 0; i < urls.size() && i < LIFE_LINK_MAX; i++) list.add(urls.get(i));
        if (list.isEmpty()) return ev("checked", 0, "dropped", 0);
        LinkedHashSet<String> dead = new LinkedHashSet<>();
        for (int i = 0; i < list.size(); i += 4) {
            List<CompletableFuture<Object[]>> futures = new ArrayList<>();
            for (int j = i; j < list.size() && j < i + 4; j++) {
                String url = list.get(j);
                futures.add(CompletableFuture.supplyAsync(() -> new Object[]{url, lifeLinkAlive(url)}, LINK_POOL));
            }
            for (CompletableFuture<Object[]> future : futures) {
                Object[] result = future.join();
                if (!Boolean.TRUE.equals(result[1])) dead.add((String) result[0]);
            }
        }
        if (dead.isEmpty()) {
            log.info("[life-link] 实测 {} 个链接全部可达", list.size());
            return ev("checked", list.size(), "dropped", 0);
        }
        for (Map<String, Object> item : items) {
            for (String field : List.of("detail", "risk")) {
                String text = str(item.get(field));
                if (text.isEmpty()) continue;
                for (String url : dead) {
                    if (text.contains(url)) text = text.replace(url, "（原链接已失效，请从该官网首页进入）");
                }
                item.put(field, text);
            }
        }
        log.info("[life-link] 实测 {} 个链接，剔除失效 {} 个：{}", list.size(), dead.size(), String.join(", ", dead));
        return ev("checked", list.size(), "dropped", dead.size());
    }

    /** HEAD 优先、被拒或超时再用 GET 复核，与 server.js 7403 的 lifeLinkAlive 一致。 */
    private boolean lifeLinkAlive(String url) {
        int head = -1;
        try {
            head = lifeHttpStatus(url, "HEAD");
        } catch (Exception ignored) {
            head = -1;
        }
        if (head >= 0) {
            if (head < 400) return true;
            if (head != 403 && head != 405 && head != 501) return false;
        }
        try {
            return lifeHttpStatus(url, "GET") < 400;
        } catch (Exception ignored) {
            return false;
        }
    }

    private int lifeHttpStatus(String url, String method) throws Exception {
        HttpRequest request = HttpRequest.newBuilder(URI.create(url))
                .timeout(Duration.ofMillis(LIFE_LINK_TIMEOUT))
                .header("User-Agent", LINK_UA)
                .method(method, HttpRequest.BodyPublishers.noBody())
                .build();
        return LINK_HTTP.send(request, HttpResponse.BodyHandlers.discarding()).statusCode();
    }

    private String buildLifeDateContext(List<Map<String, Object>> messages) {
        StringBuilder textBuilder = new StringBuilder();
        for (Map<String, Object> m : messages) textBuilder.append(str(m.get("content"))).append('\n');
        String text = textBuilder.toString();
        List<String> found = new ArrayList<>();
        for (Map<String, Object> subject : LIFE_DATE_SUBJECTS) {
            if (subject.get("keys") instanceof List<?> keys) {
                for (Object key : keys) {
                    if (text.contains(str(key))) { found.add(str(subject.get("name"))); break; }
                }
            }
        }
        if (found.isEmpty()) return "";
        String userId = currentUserId();
        int year = java.time.LocalDate.now().getYear();
        List<String> blocks = new ArrayList<>();
        for (String name : found) {
            if (blocks.size() >= 3) break;
            try {
                Object result = webSearch.multiSearch(name + " " + year + " 报名时间 笔试时间 官方公告",
                        userId, webSearch.userSecretProvider());
                // 单次检索能拿到 20+ 条，全塞进提示词会把上下文撑爆，只取前 10 条最相关的
                Map<String, Object> trimmed = new LinkedHashMap<>();
                trimmed.put("provider", fieldValue(result, "provider"));
                trimmed.put("cached", fieldValue(result, "cached"));
                List<Object> top = new ArrayList<>();
                Object rows = fieldValue(result, "results");
                if (rows instanceof List<?> rl) {
                    for (int i = 0; i < rl.size() && i < 10; i++) top.add(rl.get(i));
                }
                trimmed.put("results", top);
                String formatted = webSearch.formatSearchContext(trimmed);
                if (!formatted.isEmpty()) {
                    blocks.add("【" + name + " · 联网检索到的官方时间信息（以此为准，不要凭印象改写）】\n" + formatted);
                }
            } catch (Exception err) {
                log.warn("[life-date] {} 检索失败：{}", name, err.getMessage());
                blocks.add("【" + name + "】本次未能联网检索到官方时间，相关日期一律写「待核实：请到官方报名系统确认」，不得编造。");
            }
        }
        if (blocks.isEmpty()) return "";
        return String.join("\n", List.of(
                "【时间锚定铁律】下列日期来自实时联网检索，优先级高于你的记忆；与记忆冲突时一律采用检索结果。",
                "其中明确出现的报名截止 / 笔试 / 面试日期，必须逐条建成独立节点并写进 horizon（YYYY-MM-DD）。",
                String.join("\n\n", blocks)));
    }

