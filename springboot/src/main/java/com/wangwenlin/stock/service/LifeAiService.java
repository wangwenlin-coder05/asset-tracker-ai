    /** 按交替的 key/value 构造节点 Map（保持与 JS 对象一致的字段顺序）。 */
    private static Map<String, Object> mdNode(Object... kv) {
        Map<String, Object> m = new LinkedHashMap<>();
        for (int i = 0; i + 1 < kv.length; i += 2) m.put(String.valueOf(kv[i]), kv[i + 1]);
        return m;
    }

    private static String mdClean(String value) {
        if (value == null) return "";
        return value.replace("**", "").replace("`", "").replace("「", "").replace("」", "").trim();
    }

    private static List<String> mdCells(String row) {
        String s = row;
        if (!s.isEmpty() && (s.charAt(0) == '|' || s.charAt(0) == '｜')) s = s.substring(1);
        if (!s.isEmpty() && (s.charAt(s.length() - 1) == '|' || s.charAt(s.length() - 1) == '｜')) {
            s = s.substring(0, s.length() - 1);
        }
        List<String> out = new ArrayList<>();
        for (String part : s.split("[|｜]", -1)) out.add(mdClean(part));
        return out;
    }

    private static boolean mdAllEmpty(List<String> cells) {
        for (String cell : cells) {
            if (!cell.isEmpty() && !MD_SEP_RE.matcher(cell).matches()) return false;
        }
        return true;
    }

    private static String mdCellOf(List<String> cells, List<String> header, String[] keys) {
        int index = -1;
        for (String key : keys) {
            for (int i = 0; i < header.size(); i++) {
                if (header.get(i).contains(key)) { index = i; break; }
            }
            if (index >= 0) break;
        }
        if (index < 0 || index >= cells.size()) return "";
        return cells.get(index);
    }

    private static String mdSlice(String value, int max) {
        return value.length() <= max ? value : value.substring(0, max);
    }

    private static String mdPad2(String value) {
        return value.length() >= 2 ? value : "0".repeat(2 - value.length()) + value;
    }

    private static String mdDate(String dateText, String today) {
        Matcher m = MD_DATE_PARTS_RE.matcher(dateText);
        if (!m.find()) return today;
        return m.group(1) + "-" + mdPad2(m.group(2)) + "-" + mdPad2(m.group(3));
    }

    private static String mdPriority(String raw) {
        if (MD_PRIORITY_VALUE_RE.matcher(raw).matches()) return raw.toUpperCase(Locale.ROOT);
        if (raw.contains("高")) return "P1";
        if (raw.contains("中")) return "P2";
        if (raw.contains("低")) return "P3";
        return "P1";
    }

    /** 距今天数 → 时间分组；日期非法时与 JS 的 NaN 语义一致，一律落到 future。 */
    private static String mdTimeGroup(String date, String today) {
        Long days = null;
        try {
            days = java.time.temporal.ChronoUnit.DAYS.between(
                    java.time.LocalDate.parse(today), java.time.LocalDate.parse(date));
        } catch (Exception ignored) {
            days = null;
        }
        if (days != null && days <= 30) return "urgent";
        if (days != null && days <= 90) return "mid";
        return "future";
    }

