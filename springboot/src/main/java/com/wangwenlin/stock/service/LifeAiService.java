    private static final class PlanResult {
        List<Map<String, Object>> nodes;
        List<Map<String, Object>> anchors;
        String summary;
        boolean complete;
    }

    private PlanResult readPlan(String text) {
        Object parsed = support.parseLifeJson(text);
        if (parsed instanceof Map<?, ?> pm) {
            Map<String, Object> map = cast(pm);
            Object nodesObj = map.get("nodes");
            if (nodesObj instanceof List<?> nl && !nl.isEmpty()) {
                PlanResult r = new PlanResult();
                r.nodes = castList(nl);
                Object summary = truthy(map.get("summary")) ? map.get("summary")
                        : (truthy(map.get("reading")) ? map.get("reading") : map.get("解读"));
                r.summary = str(summary);
                r.complete = true;
                // examAnchors 是模型从联网检索结果里整理出的考试硬时间点
                List<Map<String, Object>> anchors = new ArrayList<>();
                if (map.get("examAnchors") instanceof List<?> al) {
                    for (Object a : al) if (a instanceof Map<?, ?> am) anchors.add(cast(am));
                }
                r.anchors = anchors;
                return r;
            }
        }
        List<Object> salvaged = support.salvageJsonObjects(text);
        if (salvaged != null) {
            boolean any = false;
            for (Object item : salvaged) if (item instanceof Map<?, ?> m && truthy(cast(m).get("title"))) { any = true; break; }
            if (any) {
                PlanResult r = new PlanResult();
                r.nodes = castList(salvaged);
                r.summary = support.extractLifeSummary(text);
                r.complete = false;
                return r;
            }
        }
        Object fromMd = planLifeNodesFromMarkdown(text);
        if (fromMd instanceof Map<?, ?> m) {
            Object nodesObj = cast(m).get("nodes");
            if (nodesObj instanceof List<?> nl && !nl.isEmpty()) {
                PlanResult r = new PlanResult();
                r.nodes = castList(nl);
                r.summary = support.extractLifeSummary(text);
                r.complete = false;
                return r;
            }
        }
        return null;
    }

