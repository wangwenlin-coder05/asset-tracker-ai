    /** 第三轮 op=update：逐字段动态更新（截断长度与白名单与 Node 一致）。 */
    private int applyUpdateOp(Map<String, Object> op, Map<String, String> tempIds,
                              LinkedHashSet<String> knownIds, long now) {
        // Node 直接使用 op.id 作为 WHERE 目标（不做 tempMap 换算），此处保持一致
        String id = str(op.get("id"));
        if (id.isEmpty()) return 0;
        Map<String, Object> upd = new LinkedHashMap<>();
        upd.put("id", id);
        if (op.containsKey("title")) upd.put("title", support.lifeText(op.get("title"), 200));
        if (op.containsKey("detail")) upd.put("detail", support.lifeText(op.get("detail"), 1200));
        if (op.containsKey("risk")) upd.put("risk", support.lifeText(op.get("risk"), 200));
        if (op.containsKey("priority")) {
            upd.put("priority", LifeSupport.LIFE_TASK_PRIORITY.contains(str(op.get("priority"))) ? str(op.get("priority")) : "");
        }
        if (op.containsKey("series")) upd.put("series", support.lifeText(op.get("series"), 64));
        if (op.containsKey("horizon")) upd.put("horizon", support.lifeText(op.get("horizon"), 32));
        // 开始日期：与截止日期分开更新（op.startDate || op.start_date）
        if (op.containsKey("startDate") || op.containsKey("start_date")) {
            upd.put("startDate", support.lifeText(jsOr(op.get("startDate"), op.get("start_date")), 10));
        }
        // 改挂父节点：用于合并重复赛道（把重复节点及其子树改挂到保留的那条下面）
        if (op.containsKey("parentId") || op.containsKey("parent_id")) {
            String parentKey = str(jsOr(op.get("parentId"), op.get("parent_id")));
            String target = tempIds.getOrDefault(parentKey, parentKey);
            // Node: target && target !== op.id && (target === '' || knownIds.has(target))
            // target 非空时后半段等价于 knownIds.has(target)；target 为空则整体 falsy，直接跳过（不写空串）
            if (!target.isEmpty() && !target.equals(id) && knownIds.contains(target)) {
                upd.put("parentId", target);
            }
        }
        if (op.containsKey("weight")) upd.put("weight", support.lifeClampWeight(op.get("weight")));
        if (op.containsKey("status") && List.of("todo", "doing", "done").contains(str(op.get("status")))) {
            upd.put("status", str(op.get("status")));
        }
        if (op.containsKey("domain") && LifeSupport.LIFE_DOMAINS.contains(str(op.get("domain")))) {
            upd.put("domain", str(op.get("domain")));
        }
        if (op.containsKey("timeGroup") && LifeSupport.LIFE_TIME_GROUPS.contains(str(op.get("timeGroup")))) {
            upd.put("timeGroup", str(op.get("timeGroup")));
        }
        if (op.containsKey("stepNo")) upd.put("stepNo", clampStep(op.get("stepNo")));
        if (op.get("deps") instanceof List<?> deps) {
            upd.put("deps", jsonStringify(normalizeRefList(castRawList(deps), id, tempIds, knownIds)));
        }
        if (op.get("referenceIds") instanceof List<?> refIds) {
            upd.put("referenceIds", jsonStringify(normalizeRefList(castRawList(refIds), id, tempIds, knownIds)));
        }
        if (op.containsKey("shared")) upd.put("isShared", truthy(op.get("shared")) ? 1 : 0);
        if (op.containsKey("progressNote")) upd.put("progressNote", support.lifeText(op.get("progressNote"), 1200));
        if (upd.size() <= 1) return 0;
        upd.put("updatedAt", now);
        aiMapper.updateNodeFieldsFull(upd);
        return 1;
    }

    /** 第三轮 op=remove：只允许 AI 移除自己生成的、且不是「大脑」的节点。 */
    private int applyRemoveOp(Map<String, Object> op, Map<String, String> tempIds) {
        // Node 直接使用 op.id 作为 WHERE 目标（不做 tempMap 换算）
        String id = str(op.get("id"));
        if (id.isEmpty()) return 0;
        Map<String, Object> row = aiMapper.selectSourceKindById(id);
        if (row == null || !"ai".equals(str(row.get("source")))) return 0;
        if ("self".equals(str(row.get("kind")))) return 0;
        aiMapper.deleteNodeById(id);
        return 1;
    }

    /** tempMap 换算 + 剔除悬空引用 + 去重，与 Node 的 deps / referenceIds 处理一致。 */
    private static List<String> normalizeRefList(List<Object> refs, String selfId,
                                                Map<String, String> tempIds, Set<String> knownIds) {
        LinkedHashSet<String> out = new LinkedHashSet<>();
        for (Object ref : refs) {
            String mapped = tempIds.getOrDefault(str(ref), str(ref));
            if (!mapped.isEmpty() && !mapped.equals(selfId) && knownIds.contains(mapped)) out.add(mapped);
        }
        return new ArrayList<>(out);
    }

