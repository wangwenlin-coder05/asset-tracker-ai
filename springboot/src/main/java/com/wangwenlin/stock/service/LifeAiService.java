    private Map<String, Object> mergeLifeSearches(List<Map<String, Object>> items) {
        if (items == null || items.isEmpty()) return null;
        List<Map<String, Object>> results = new ArrayList<>();
        Set<String> seen = new HashSet<>();
        String provider = "";
        boolean allCached = true;
        List<String> queries = new ArrayList<>();
        for (Map<String, Object> item : items) {
            Map<String, Object> found = item.get("search") instanceof Map<?, ?> m ? cast(m) : new LinkedHashMap<>();
            if (provider.isEmpty() && truthy(found.get("provider"))) provider = str(found.get("provider"));
            if (!truthy(found.get("cached"))) allCached = false;
            if (found.get("results") instanceof List<?> rows) {
                for (Object r : rows) {
                    if (!(r instanceof Map<?, ?> rm)) continue;
                    Map<String, Object> row = cast(rm);
                    String url = str(row.get("url"));
                    if (!url.isEmpty() && seen.contains(url)) continue;
                    if (!url.isEmpty()) seen.add(url);
                    results.add(row);
                }
            }
            queries.add(str(item.get("query")));
        }
        Map<String, Object> out = new LinkedHashMap<>();
        out.put("provider", provider);
        out.put("cached", allCached);
        out.put("query", String.join(" / ", queries));
        out.put("queries", queries);
        out.put("count", results.size());
        out.put("results", results);
        return out;
    }

    private Map<String, Object> toSearchPayload(Object searchObj) {
        if (!(searchObj instanceof Map<?, ?> m)) return null;
        Map<String, Object> search = cast(m);
        List<Map<String, Object>> results = new ArrayList<>();
        if (search.get("results") instanceof List<?> rows) {
            for (Object r : rows) if (r instanceof Map<?, ?> rm) results.add(cast(rm));
        }
        List<String> queries = new ArrayList<>();
        if (search.get("queries") instanceof List<?> ql) {
            for (Object q : ql) queries.add(str(q));
        } else if (truthy(search.get("query"))) {
            queries.add(str(search.get("query")));
        }
        Map<String, Object> out = new LinkedHashMap<>();
        out.put("provider", str(search.get("provider")));
        out.put("cached", truthy(search.get("cached")));
        out.put("count", results.size());
        out.put("query", str(search.get("query")));
        out.put("queries", queries);
        List<Map<String, Object>> sources = new ArrayList<>();
        for (Map<String, Object> r : results) {
            Map<String, Object> s = new LinkedHashMap<>();
            s.put("title", str(r.get("title")));
            s.put("url", str(r.get("url")));
            s.put("snippet", str(r.get("snippet")));
            sources.add(s);
        }
        out.put("sources", sources);
        return out;
    }

